import asyncHandler from "express-async-handler";
import RecurringExpense from "../models/recurringExpense.js";
import Expense from "../models/expense.js";

// Helper to check and generate monthly expenses for active recurring templates
export async function processRecurringExpenses(userId) {
  const now = new Date();
  const currentMonth = now.getMonth();
  const currentYear = now.getFullYear();

  const activeRecurring = await RecurringExpense.find({ user: userId, isActive: true });

  for (const item of activeRecurring) {
    let shouldGenerate = false;

    if (!item.lastGeneratedDate) {
      shouldGenerate = true;
    } else {
      const lastGen = new Date(item.lastGeneratedDate);
      if (lastGen.getFullYear() < currentYear || (lastGen.getFullYear() === currentYear && lastGen.getMonth() < currentMonth)) {
        shouldGenerate = true;
      }
    }

    if (shouldGenerate) {
      // Create actual expense entry for the current month
      await Expense.create({
        amount: item.amount,
        description: `${item.description} (Recurring)`,
        category: item.category || 'Bills & Utilities',
        user: userId,
        isAutoGenerated: true,
        createdAt: new Date(currentYear, currentMonth, 1) // Set date to 1st of current month
      });

      // Update last generated date
      item.lastGeneratedDate = now;
      await item.save();
    }
  }
}

// @desc    Get all recurring expenses for user
// @route   GET /api/recurring
// @access  Private
const getRecurringExpenses = asyncHandler(async (req, res) => {
  // Trigger auto-generation check whenever user fetches recurring items
  await processRecurringExpenses(req.user._id);

  const recurring = await RecurringExpense.find({ user: req.user._id }).sort({ createdAt: -1 });
  res.status(200).json({ success: true, recurring });
});

// @desc    Create a recurring expense template
// @route   POST /api/recurring
// @access  Private
const createRecurringExpense = asyncHandler(async (req, res) => {
  const { amount, description, category, frequency, billingDate } = req.body;

  if (!billingDate) {
    res.status(400);
    throw new Error('Billing date is required');
  }

  const recurring = await RecurringExpense.create({
    user: req.user._id,
    amount,
    description,
    category,
    billingDay: Number(billingDate),
    frequency: frequency || 'monthly'
  });

  res.status(201).json({ success: true, recurring });
});

// @desc    Toggle active status or delete recurring expense
// @route   DELETE /api/recurring/:id
// @access  Private
const deleteRecurringExpense = asyncHandler(async (req, res) => {
  const recurring = await RecurringExpense.findById(req.params.id);

  if (!recurring || recurring.user.toString() !== req.user._id.toString()) {
    res.status(404);
    throw new Error("Recurring expense not found");
  }

  await RecurringExpense.deleteOne({ _id: req.params.id });
  res.status(200).json({ success: true, message: "Recurring expense removed" });
});

export {
  getRecurringExpenses,
  createRecurringExpense,
  deleteRecurringExpense
};