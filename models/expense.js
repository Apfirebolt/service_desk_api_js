
import mongoose from "mongoose";

const expenseSchema = new mongoose.Schema({
  amount: {
    type: Number,
    required: true
  },
  type: {
    type: String,
    required: true
  },
  description: {
    type: String,
    required: true
  },
  category: {
    type: String,
    required: false
  },
  isSplit: {
    type: Boolean,
    required: false,
    default: false
  },
  isAutoGenerated: {
    type: Boolean,
    required: false,
    default: false
  },
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  }
}, { timestamps: true });

const Expense = mongoose.model('Expense', expenseSchema)

export default Expense
