import mongoose from "mongoose";

const expenseSchema = new mongoose.Schema({
  amount: {
    type: Number,
    required: true
  },
  mode: {
    type: String,
    required: false
  },
  description: {
    type: String,
    required: true
  },
  category: {
    type: String,
    required: false
  },
  isSplit: {
    type: Boolean,
    required: false,
    default: false
  },
  isAutoGenerated: {
    type: Boolean,
    required: false,
    default: false
  },
  roomId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'ExpenseRoom',
    required: false
  },
  // Who created/logged the expense record
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  // NEW: Who actually paid for the expense (defaults to the creator if not specified)
  paidBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: false
  },
  // NEW: Array of user IDs specifying who is splitting this expense
  splitBetween: [{
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: false
  }],
  isPaid: {
    type: Boolean,
    required: false,
    default: false
  }
}, { timestamps: true });

const Expense = mongoose.model('Expense', expenseSchema);

export default Expense;