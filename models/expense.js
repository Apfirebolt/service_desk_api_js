import mongoose from "mongoose";

const expenseSchema = new mongoose.Schema({
  amount: {
    type: Number,
    required: true
  },
  mode: {
    type: String,
    required: false
  },
  description: {
    type: String,
    required: true
  },
  category: {
    type: String,
    required: false
  },
  isSplit: {
    type: Boolean,
    required: false,
    default: false
  },
  isAutoGenerated: {
    type: Boolean,
    required: false,
    default: false
  },
  roomId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'ExpenseRoom',
    required: false
  },
  user: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true
  },
  paidBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: false
  },
  splitBetween: [{
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: false
  }],
  isPaid: {
    type: Boolean,
    required: false,
    default: false
  },
  settlementStatus: {
    type: String,
    enum: ["unpaid", "pending_confirmation", "settled"],
    default: "unpaid",
    required: false
  },
  confirmedBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: false
  }
}, { timestamps: true });

const Expense = mongoose.models.Expense || mongoose.model('Expense', expenseSchema);

export default Expense;